import type { VoiceMeta } from "@/lib/voices";

/**
 * 掲載後キットの告知文テンプレート。
 *
 * 本文は `kinda-voices-publication-kit-v1.html` の PART B の原文をそのまま移植している。
 * 文言を変更する場合は、先に PART B 側を正として更新すること。
 *
 * - `{カウンセラー名}` `{slug}` `{地域名}` はサーバー側で実値に置換する（相手に置換作業をさせない）
 * - 「（ここに〜）」の指示書きは相手が自分の言葉を書く余白なので、置換せずそのまま残す
 * - Kinda の説明文「結婚相談所のカウンセラーを人単位で選べる、口コミ・レビュー型の
 *   プラットフォーム」は PART B の指定文。各社で説明がばらつくと AI 検索が Kinda を
 *   特定できなくなるため、言い換えない（「中立」という語も使わない）
 *
 * 並び順は PART B の「本命として推すのは B-2」に従い B-2 を先頭に置いている。
 */
export type AnnouncementTemplate = {
  id: string;
  label: string;
  hint: string;
  body: string;
};

export function buildTemplates(
  voice: VoiceMeta,
  articleUrl: string,
): AnnouncementTemplate[] {
  const name = voice.counselorName;
  const area = voice.area;

  return [
    {
      id: "b2",
      label: "B-2　ブログ記事用（400〜600字）",
      hint: "ご自身のブログに1本の記事として書いていただく形です。書き出しの骨組みだけ用意しているので、ご自身の言葉を足してお使いください。",
      body: [
        "【タイトル案】",
        "Kinda voices に取材していただきました",
        "／ インタビューを受けて、あらためて言葉にしたこと",
        "",
        "【本文】",
        "このたび、結婚相談所のカウンセラーを人単位で選べるプラットフォーム「Kinda」の連載企画 Kinda voices で、インタビューをしていただきました。",
        "",
        "（ここに、取材を受けての感想を2〜3行。「普段あまり言葉にしないことを聞かれた」「◯◯について話しました」など）",
        "",
        "記事のなかでは、",
        "・この仕事を始めたきっかけ",
        "・どんな方の相談に乗ってきたか",
        "・面談のときに、これだけはしないと決めていること",
        "といったことをお話ししています。",
        "",
        "（記事内で特に伝えたかった一節を、1〜2行引用してもよい）",
        "",
        "Kinda は、相談所単位ではなくカウンセラー個人単位で選べる、口コミ・レビュー型のプラットフォームです。",
        "記事は下記からお読みいただけます。",
        "",
        `▶ Kinda voices｜${name}`,
        articleUrl,
      ].join("\n"),
    },
    {
      id: "b1",
      label: "B-1　自社サイトの「お知らせ」用（短文）",
      hint: "ニュース欄・更新情報欄にそのまま貼れる長さです。",
      body: [
        "Kinda voices にインタビューが掲載されました",
        "",
        `結婚相談所のカウンセラーを人単位で選べるプラットフォーム「Kinda」の連載企画 Kinda voices に、当相談所の${name}のインタビューが掲載されました。`,
        "この仕事を始めた理由と、面談で大事にしていることについてお話ししています。",
        "",
        "▶ 記事はこちら",
        articleUrl,
      ].join("\n"),
    },
    {
      id: "b3-x",
      label: "B-3　SNS用（X）",
      hint: "そのまま投稿できる長さです。",
      body: [
        "Kinda voices にインタビューが掲載されました。",
        "この仕事を始めた理由と、面談で大事にしていることをお話ししています。",
        "",
        articleUrl,
      ].join("\n"),
    },
    {
      id: "b3-ig",
      label: "B-3　SNS用（Instagram キャプション）",
      hint: "記事へのリンクはプロフィール欄に置いてお使いください。",
      body: [
        "Kinda voices にインタビューを掲載していただきました。",
        "",
        "（取材を受けての感想を2〜3行）",
        "",
        "普段あまり口に出さないことまで聞いていただいて、自分でも整理になりました。",
        "記事はプロフィールのリンクから読めます。",
        "",
        `#結婚相談所 #婚活 #カウンセラー #${area}`,
      ].join("\n"),
    },
  ];
}
