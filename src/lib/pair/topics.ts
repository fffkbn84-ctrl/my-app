/** 層ごとの話題（定義順を保つ） */
export function topicsByLayer(layer: PairLayer): PairTopic[] {
  return PAIR_TOPICS.filter((t) => t.layer === layer);
}

/** key 引き（結果画面の復元用） */
export function findTopic(key: string): PairTopic | undefined {
  return PAIR_TOPICS.find((t) => t.key === key);
}

